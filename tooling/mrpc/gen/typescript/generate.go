// Package typescriptgen generates environment-neutral TypeScript MRPC bindings.
package typescriptgen

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/d7z-team/mini-go/tooling/mrpc"
	"github.com/d7z-team/mini-go/tooling/mrpc/gen"
)

// Options controls source-level imports and names without changing wire identity.
type Options struct {
	Runtime string
	Prefix  string
}

// Generate returns deterministic TypeScript ESM source.
func Generate(catalog mrpc.Catalog, options Options) ([]byte, error) {
	canonical, err := gen.CanonicalCatalog(catalog)
	if err != nil {
		return nil, fmt.Errorf("generate TypeScript MRPC: %w", err)
	}
	if options.Runtime == "" {
		options.Runtime = canonical.Options["ts_runtime"]
	}
	if options.Runtime == "" {
		options.Runtime = "@d7z-team/mini-go/rpc"
	}
	options.Runtime = strings.TrimSpace(options.Runtime)
	if options.Prefix == "" {
		options.Prefix = canonical.Options["ts_prefix"]
	}
	options.Prefix = strings.TrimSpace(options.Prefix)
	if !validModule(options.Runtime) {
		return nil, errors.New("generate TypeScript MRPC: valid ts_runtime module is required")
	}

	g := generator{
		catalog: canonical,
		options: options,
		imports: make(map[string]mrpc.Catalog),
	}
	paths := make(map[string]string)
	for _, file := range canonical.Files {
		for _, imported := range file.Imports {
			dependency := canonical.Dependencies[imported.Path]
			module := strings.TrimSpace(dependency.Options["ts_module"])
			if !validModule(module) {
				return nil, fmt.Errorf("generate TypeScript MRPC: import %q has no valid ts_module", imported.Path)
			}
			prefix := strings.TrimSpace(dependency.Options["ts_prefix"])
			if prefix != "" && !validIdentifier(pascal(prefix)) {
				return nil, fmt.Errorf("generate TypeScript MRPC: import %q has invalid ts_prefix %q", imported.Path, prefix)
			}
			dependency.Options["ts_prefix"] = prefix
			g.imports[imported.Alias] = dependency
			paths[imported.Alias] = module
		}
	}
	if err := g.validateNames(); err != nil {
		return nil, err
	}

	g.line("// Code generated by mini-go rpc generate; DO NOT EDIT.")
	g.line("import {")
	for _, name := range []string{
		"RPCStatus", "bytesCodec", "enumCodec", "lazyCodec", "localResource", "mapCodec",
		"messageCodec", "optionalCodec", "providedResource", "rpcCodecs", "sliceCodec",
	} {
		g.line("  %s,", name)
	}
	for _, name := range []string{
		"RPCBindOptions", "RPCBinding", "RPCCallOptions", "RPCCodec", "RPCConnection",
		"RPCComplex", "RPCContract", "RPCMethod", "RPCProvider", "RPCResource", "RPCResourceDescriptor",
		"RPCServerContext", "RPCValue",
	} {
		g.line("  type %s,", name)
	}
	g.line("} from %s;", quote(options.Runtime))
	aliases := make([]string, 0, len(paths))
	for alias := range paths {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		g.line("import * as %s from %s;", alias, quote(paths[alias]))
	}
	g.line("")
	g.line("export const MRPC_CONTRACT_ID = %s;", quote(canonical.ContractID))

	for _, file := range canonical.Files {
		for _, item := range file.Enums {
			g.enum(item)
		}
		for _, item := range file.Messages {
			g.message(item)
		}
		for _, item := range file.Resources {
			g.resource(item)
		}
		for _, item := range file.Services {
			g.service(item)
		}
	}
	if g.err != nil {
		return nil, fmt.Errorf("generate TypeScript MRPC: %w", g.err)
	}
	return g.source.Bytes(), nil
}

type generator struct {
	catalog mrpc.Catalog
	options Options
	imports map[string]mrpc.Catalog
	source  bytes.Buffer
	err     error
}

func (g *generator) line(format string, args ...any) {
	fmt.Fprintf(&g.source, format+"\n", args...)
}

func (g *generator) doc(text, indent string) {
	if text == "" {
		return
	}
	g.line("%s/**", indent)
	for _, line := range strings.Split(strings.ReplaceAll(text, "*/", "* /"), "\n") {
		g.line("%s * %s", indent, line)
	}
	g.line("%s */", indent)
}

func (g *generator) name(name string) string { return pascal(g.options.Prefix) + pascal(name) }

func (g *generator) importedName(alias, name string) string {
	return pascal(g.imports[alias].Options["ts_prefix"]) + pascal(name)
}

func (g *generator) named(typ mrpc.Type) string {
	if typ.Qualifier != "" {
		return typ.Qualifier + "." + g.importedName(typ.Qualifier, typ.Name)
	}
	return g.name(typ.Name)
}

func (g *generator) resolve(typ mrpc.Type) mrpc.ResolvedType {
	resolved, err := g.catalog.ResolveType(typ)
	if err != nil && g.err == nil {
		g.err = err
	}
	return resolved
}

func (g *generator) resourceType(typ mrpc.Type) (mrpc.ResolvedType, bool) {
	if typ.Kind != mrpc.TypeName {
		return mrpc.ResolvedType{}, false
	}
	resolved := g.resolve(typ)
	return resolved, resolved.Resource != nil
}

func (g *generator) wire(typ mrpc.Type) string {
	value, err := g.catalog.CanonicalType(typ)
	if err != nil && g.err == nil {
		g.err = err
	}
	return value
}

func (g *generator) resourceHash(typ mrpc.Type) string {
	resolved, ok := g.resourceType(typ)
	if !ok {
		if g.err == nil {
			g.err = fmt.Errorf("%s is not an MRPC resource", typ.String())
		}
		return ""
	}
	return resolved.Owner.ResourceTypeID(resolved.Name)
}

func (g *generator) tsType(typ mrpc.Type, provider bool) string {
	switch typ.Kind {
	case mrpc.TypeSlice:
		if typ.Elem.Kind == mrpc.TypeName && typ.Elem.Qualifier == "" && typ.Elem.Name == "uint8" {
			return "Uint8Array | null"
		}
		return "Array<" + g.tsType(*typ.Elem, provider) + "> | null"
	case mrpc.TypeMap:
		return "Map<" + g.tsType(*typ.Key, provider) + ", " + g.tsType(*typ.Elem, provider) + "> | null"
	case mrpc.TypeOptional:
		return g.tsType(*typ.Elem, provider) + " | undefined"
	}
	if _, resource := g.resourceType(typ); resource {
		suffix := "Client"
		if provider {
			suffix = "Handler"
		}
		return g.named(typ) + suffix + " | null"
	}
	if typ.Qualifier != "" {
		return g.named(typ)
	}
	switch typ.Name {
	case "bool":
		return "boolean"
	case "string":
		return "string"
	case "int64", "uint64":
		return "bigint"
	case "complex64", "complex128":
		return "RPCComplex"
	case "int8", "int16", "int32", "uint8", "uint16", "uint32", "float32", "float64":
		return "number"
	default:
		return g.named(typ)
	}
}

func (g *generator) codec(typ mrpc.Type) string {
	wire := quote(g.wire(typ))
	switch typ.Kind {
	case mrpc.TypeSlice:
		if typ.Elem.Kind == mrpc.TypeName && typ.Elem.Qualifier == "" && typ.Elem.Name == "uint8" {
			return "bytesCodec(" + wire + ")"
		}
		return "sliceCodec(" + wire + ", " + g.codec(*typ.Elem) + ")"
	case mrpc.TypeMap:
		return "mapCodec(" + wire + ", " + g.codec(*typ.Key) + ", " + g.codec(*typ.Elem) + ")"
	case mrpc.TypeOptional:
		return "optionalCodec(" + wire + ", " + g.codec(*typ.Elem) + ")"
	}
	resolved := g.resolve(typ)
	if resolved.Kind == "scalar" {
		return "rpcCodecs." + typ.Name
	}
	if resolved.Resource != nil {
		if g.err == nil {
			g.err = fmt.Errorf("resource %s has no value codec", typ.String())
		}
		return "rpcCodecs.string"
	}
	return "lazyCodec(() => " + g.named(typ) + "Codec)"
}

func (g *generator) enum(item mrpc.Enum) {
	name := g.name(item.Name)
	g.line("")
	g.doc(item.Doc, "")
	g.line("export type %s = number;", name)
	g.line("export const %s = {", name)
	for _, value := range item.Values {
		g.doc(value.Doc, "  ")
		g.line("  %s: %d,", pascal(value.Name), value.Number)
	}
	g.line("} as const;")
	g.line("export const %sCodec: RPCCodec<%s> = enumCodec(%s);", name, name, quote(g.catalog.Namespace+"."+item.Name))
}

func (g *generator) message(item mrpc.Message) {
	name := g.name(item.Name)
	g.line("")
	g.doc(item.Doc, "")
	g.line("export interface %s {", name)
	for _, field := range item.Fields {
		g.doc(field.Doc, "  ")
		g.line("  %s: %s;", lowerCamel(field.Name), g.tsType(field.Type, false))
	}
	g.line("}")
	g.line("export const %sCodec: RPCCodec<%s> = messageCodec<%s>(%s, [", name, name, name, quote(g.catalog.Namespace+"."+item.Name))
	for _, field := range item.Fields {
		g.line("  { id: %d, name: %s, codec: %s as RPCCodec<unknown> },", field.ID, quote(lowerCamel(field.Name)), g.codec(field.Type))
	}
	g.line("]);")
}

func (g *generator) method(owner mrpc.Catalog, service, method, resourceHash string) string {
	service = owner.Namespace + "::" + service
	return fmt.Sprintf("{ id: %s, service: %s, name: %s, contractHash: %s, resourceTypeHash: %s }", quote(service+"."+method), quote(service), quote(method), quote(owner.ContractID), quote(resourceHash))
}

func (g *generator) methodConstant(owner, method string) string {
	return lowerCamel(g.name(owner)) + pascal(method) + "Method"
}

func (g *generator) emitMethodConstants(owner string, methods []mrpc.Method, resource bool) {
	hash := ""
	if resource {
		hash = g.catalog.ResourceTypeID(owner)
	}
	for _, method := range methods {
		g.line("const %s: RPCMethod = %s;", g.methodConstant(owner, method.Name), g.method(g.catalog, owner, method.Name, hash))
	}
}

func (g *generator) signature(method mrpc.Method, provider, readonly bool) string {
	switch len(method.Results) {
	case 0:
		return "void"
	case 1:
		return g.tsType(method.Results[0].Type, provider)
	default:
		prefix := ""
		if readonly {
			prefix = "readonly "
		}
		parts := make([]string, len(method.Results))
		for i, field := range method.Results {
			parts[i] = lowerCamel(field.Name) + ": " + g.tsType(field.Type, provider)
		}
		return prefix + "[" + strings.Join(parts, ", ") + "]"
	}
}

func (g *generator) handlerMethod(method mrpc.Method) {
	params := []string{"context: RPCServerContext"}
	for _, field := range method.Params {
		params = append(params, lowerCamel(field.Name)+": "+g.tsType(field.Type, true))
	}
	result := g.signature(method, true, true)
	g.doc(method.Doc, "  ")
	g.line("  %s(%s): %s | Promise<%s>;", lowerCamel(method.Name), strings.Join(params, ", "), result, result)
}

func (g *generator) decode(typ mrpc.Type, expression string, provider bool, binding string) string {
	if _, resource := g.resourceType(typ); resource {
		if provider {
			return fmt.Sprintf("localResource(%s, %s, %sResourceDescriptor)", expression, quote(g.resourceHash(typ)), g.named(typ))
		}
		return fmt.Sprintf("%sClient.from(%s, %s)", g.named(typ), binding, expression)
	}
	return g.codec(typ) + ".decode(" + expression + ")"
}

func (g *generator) encode(typ mrpc.Type, expression string, provider bool) string {
	if _, resource := g.resourceType(typ); resource {
		hash := quote(g.resourceHash(typ))
		if provider {
			return fmt.Sprintf("providedResource(%s, %sResourceDescriptor, %s)", hash, g.named(typ), expression)
		}
		return fmt.Sprintf("%s === null ? { type: %s, data: { kind: \"nil\" } } : %s.toValue()", expression, hash, expression)
	}
	return g.codec(typ) + ".encode(" + expression + ")"
}

func (g *generator) invokeHandler(handler string, method mrpc.Method) {
	g.line("      if (arguments_.length !== %d)", len(method.Params))
	g.line("        throw new RPCStatus(\"invalid_argument\", \"invalid MRPC argument count\");")
	args := []string{"context"}
	for i, field := range method.Params {
		name := "argument" + strconv.Itoa(i)
		g.line("      const %s = %s;", name, g.decode(field.Type, fmt.Sprintf("arguments_[%d]", i), true, ""))
		args = append(args, name)
	}
	if len(method.Results) == 0 {
		g.line("      await %s.%s(%s);", handler, lowerCamel(method.Name), strings.Join(args, ", "))
		g.line("      return [];")
		return
	}
	g.line("      const result = await %s.%s(%s);", handler, lowerCamel(method.Name), strings.Join(args, ", "))
	if len(method.Results) > 1 {
		g.line("      if (!Array.isArray(result) || result.length !== %d)", len(method.Results))
		g.line("        throw new RPCStatus(\"internal\", \"MRPC handler returned an invalid result tuple\");")
	}
	g.line("      return [")
	for i, field := range method.Results {
		expression := "result"
		if len(method.Results) > 1 {
			expression = fmt.Sprintf("result[%d]", i)
		}
		g.line("        %s,", g.encode(field.Type, expression, true))
	}
	g.line("      ];")
}

func (g *generator) clientMethod(target, owner string, method mrpc.Method) {
	params := make([]string, 0, len(method.Params)+1)
	for _, field := range method.Params {
		params = append(params, lowerCamel(field.Name)+": "+g.tsType(field.Type, false))
	}
	params = append(params, "options: RPCCallOptions = {}")
	g.doc(method.Doc, "  ")
	g.line("  %s(%s): Promise<%s> {", lowerCamel(method.Name), strings.Join(params, ", "), g.signature(method, false, false))
	g.line("    return this.%s.invoke(", target)
	g.line("      %s,", g.methodConstant(owner, method.Name))
	g.line("      [")
	for _, field := range method.Params {
		name := lowerCamel(field.Name)
		g.line("        %s,", g.encode(field.Type, name, false))
	}
	g.line("      ],")
	g.line("      (values) => {")
	g.line("        if (values.length !== %d)", len(method.Results))
	g.line("          throw new RPCStatus(\"protocol\", \"invalid MRPC result count\");")
	if len(method.Results) == 0 {
		g.line("        return;")
	} else if len(method.Results) == 1 {
		g.line("        return %s;", g.decode(method.Results[0].Type, "values[0]", false, "this.binding"))
	} else {
		g.line("        return [")
		for i, field := range method.Results {
			g.line("          %s,", g.decode(field.Type, fmt.Sprintf("values[%d]", i), false, "this.binding"))
		}
		g.line("        ];")
	}
	g.line("      },")
	g.line("      options,")
	g.line("    );")
	g.line("  }")
}

func (g *generator) resource(item mrpc.Resource) {
	name := g.name(item.Name)
	hash := g.catalog.ResourceTypeID(item.Name)
	g.line("")
	g.emitMethodConstants(item.Name, item.Methods, true)
	g.doc(item.Doc, "")
	g.line("export interface %sHandler {", name)
	for _, method := range item.Methods {
		g.handlerMethod(method)
	}
	g.line("  close(): void | Promise<void>;")
	g.line("}")
	g.line("")
	g.line("export const %sResourceDescriptor: RPCResourceDescriptor<%sHandler> = {", name, name)
	g.line("  typeHash: %s,", quote(hash))
	g.line("  async invoke(handler, context, method, arguments_) {")
	g.line("    switch (method) {")
	for _, method := range item.Methods {
		g.line("    case %s: {", quote(method.Name))
		g.invokeHandler("handler", method)
		g.line("    }")
	}
	g.line("    default:")
	g.line("      throw new RPCStatus(\"unimplemented\", `unknown MRPC resource method ${method}`);")
	g.line("    }")
	g.line("  },")
	g.line("  close(handler) {")
	g.line("    return handler.close();")
	g.line("  },")
	g.line("};")
	g.line("")
	g.line("export class %sClient {", name)
	g.line("  private constructor(")
	g.line("    private readonly binding: RPCBinding,")
	g.line("    private readonly resource: RPCResource,")
	g.line("  ) {}")
	g.line("  static from(binding: RPCBinding, value: RPCValue): %sClient | null {", name)
	g.line("    const resource = binding.resource(value, %s);", quote(hash))
	g.line("    return resource === null ? null : new %sClient(binding, resource);", name)
	g.line("  }")
	g.line("  toValue(): RPCValue {")
	g.line("    return this.resource.value();")
	g.line("  }")
	for _, method := range item.Methods {
		g.clientMethod("resource", item.Name, method)
	}
	g.line("  close(options: RPCCallOptions = {}): Promise<void> {")
	g.line("    return this.resource.close(options);")
	g.line("  }")
	g.line("}")
}

func (g *generator) service(item mrpc.Service) {
	name := g.name(item.Name)
	g.line("")
	g.emitMethodConstants(item.Name, item.Methods, false)
	g.doc(item.Doc, "")
	g.line("export interface %sHandler {", name)
	for _, method := range item.Methods {
		g.handlerMethod(method)
	}
	g.line("}")
	g.line("")
	g.line("export const %sContract: RPCContract = {", name)
	g.line("  protocol: \"minigo.rpc.contract.v2\",")
	g.line("  methods: [")
	seen := make(map[string]bool)
	for _, method := range item.Methods {
		literal := g.method(g.catalog, item.Name, method.Name, "")
		g.line("    %s,", literal)
		seen[literal] = true
	}
	for _, resource := range g.catalog.ServiceResources(item) {
		for _, method := range resource.Methods {
			literal := g.method(resource.Owner, resource.Name, method.Name, resource.Owner.ResourceTypeID(resource.Name))
			if !seen[literal] {
				g.line("    %s,", literal)
				seen[literal] = true
			}
		}
	}
	g.line("  ],")
	g.line("};")
	g.line("")
	g.line("export function create%sProvider(handler: %sHandler): RPCProvider {", name, name)
	g.line("  return {")
	g.line("    contract: %sContract,", name)
	g.line("    async invoke(context, method, arguments_) {")
	g.line("      switch (method) {")
	for _, method := range item.Methods {
		service := g.catalog.Namespace + "::" + item.Name
		g.line("      case %s: {", quote(service+"."+method.Name))
		g.invokeHandler("handler", method)
		g.line("      }")
	}
	g.line("      default:")
	g.line("        throw new RPCStatus(\"unimplemented\", `unknown MRPC service method ${method}`);")
	g.line("      }")
	g.line("    },")
	g.line("  };")
	g.line("}")
	g.line("")
	g.line("export class %sClient {", name)
	g.line("  private constructor(private readonly binding: RPCBinding) {}")
	g.line("  static async bind(")
	g.line("    connection: RPCConnection,")
	g.line("    options: RPCBindOptions = {},")
	g.line("  ): Promise<%sClient> {", name)
	g.line("    return new %sClient(await connection.bind(%sContract, options));", name, name)
	g.line("  }")
	for _, method := range item.Methods {
		g.clientMethod("binding", item.Name, method)
	}
	g.line("  close(): Promise<void> {")
	g.line("    return this.binding.close();")
	g.line("  }")
	g.line("}")
}

func (g *generator) validateNames() error {
	if g.options.Prefix != "" && !validIdentifier(pascal(g.options.Prefix)) {
		return fmt.Errorf("generate TypeScript MRPC: invalid prefix %q", g.options.Prefix)
	}
	reservedImports := map[string]bool{}
	for _, name := range []string{
		"RPCStatus", "RPCBindOptions", "RPCBinding", "RPCCallOptions", "RPCCodec", "RPCConnection",
		"RPCComplex", "RPCContract", "RPCMethod", "RPCProvider", "RPCResource", "RPCResourceDescriptor",
		"RPCServerContext", "RPCValue", "bytesCodec", "enumCodec", "lazyCodec", "localResource",
		"mapCodec", "messageCodec", "optionalCodec", "providedResource", "rpcCodecs", "sliceCodec",
		"MRPC_CONTRACT_ID",
	} {
		reservedImports[name] = true
	}
	for alias := range g.imports {
		if !validIdentifier(alias) || reservedImports[alias] {
			return fmt.Errorf("generate TypeScript MRPC: invalid or colliding import alias %q", alias)
		}
		reservedImports[alias] = true
	}
	seen := reservedImports
	register := func(name string) error {
		if !validIdentifier(name) || seen[name] {
			return fmt.Errorf("generate TypeScript MRPC: declaration name collision %q", name)
		}
		seen[name] = true
		return nil
	}
	checkFields := func(owner string, fields []mrpc.Field) error {
		names := make(map[string]bool)
		for _, field := range fields {
			name := lowerCamel(field.Name)
			if !validIdentifier(name) || names[name] {
				return fmt.Errorf("generate TypeScript MRPC: %s field name collision %q", owner, name)
			}
			names[name] = true
		}
		return nil
	}
	checkMethods := func(owner string, methods []mrpc.Method, resource bool) error {
		used := map[string]bool{
			"binding": true, "close": true, "constructor": true, "then": true,
		}
		if !resource {
			used["bind"] = true
		} else {
			used["resource"] = true
			used["toValue"] = true
		}
		for _, method := range methods {
			name := lowerCamel(method.Name)
			if !validIdentifier(name) || used[name] {
				return fmt.Errorf("generate TypeScript MRPC: %s method name collision %q", owner, name)
			}
			used[name] = true
			if err := checkFields(owner+"."+method.Name+" request", method.Params); err != nil {
				return err
			}
			for _, field := range method.Params {
				name := lowerCamel(field.Name)
				if name == "context" || name == "options" {
					return fmt.Errorf("generate TypeScript MRPC: %s.%s parameter name collision %q", owner, method.Name, name)
				}
			}
			if err := checkFields(owner+"."+method.Name+" response", method.Results); err != nil {
				return err
			}
		}
		return nil
	}
	for _, file := range g.catalog.Files {
		for _, item := range file.Enums {
			name := g.name(item.Name)
			if err := register(name); err != nil {
				return err
			}
			if err := register(name + "Codec"); err != nil {
				return err
			}
			values := make(map[string]bool)
			for _, value := range item.Values {
				name := pascal(value.Name)
				if !validIdentifier(name) || values[name] {
					return fmt.Errorf("generate TypeScript MRPC: enum value name collision %q", name)
				}
				values[name] = true
			}
		}
		for _, item := range file.Messages {
			name := g.name(item.Name)
			if err := register(name); err != nil {
				return err
			}
			if err := register(name + "Codec"); err != nil {
				return err
			}
			if err := checkFields(item.Name, item.Fields); err != nil {
				return err
			}
		}
		for _, item := range file.Resources {
			name := g.name(item.Name)
			for _, suffix := range []string{"Handler", "ResourceDescriptor", "Client"} {
				if err := register(name + suffix); err != nil {
					return err
				}
			}
			if err := checkMethods(item.Name, item.Methods, true); err != nil {
				return err
			}
			for _, method := range item.Methods {
				if err := register(g.methodConstant(item.Name, method.Name)); err != nil {
					return err
				}
			}
		}
		for _, item := range file.Services {
			name := g.name(item.Name)
			for _, declaration := range []string{name + "Handler", name + "Contract", "create" + name + "Provider", name + "Client"} {
				if err := register(declaration); err != nil {
					return err
				}
			}
			if err := checkMethods(item.Name, item.Methods, false); err != nil {
				return err
			}
			for _, method := range item.Methods {
				if err := register(g.methodConstant(item.Name, method.Name)); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func quote(value string) string { return strconv.Quote(value) }

func validModule(value string) bool {
	value = strings.TrimSpace(value)
	return value != "" && !strings.ContainsAny(value, "\x00\r\n\u2028\u2029")
}

func validIdentifier(value string) bool {
	if value == "" || tsKeywords[value] {
		return false
	}
	for i, r := range value {
		if r != '_' && r != '$' && !unicode.IsLetter(r) && (i == 0 || !unicode.IsDigit(r)) {
			return false
		}
	}
	return true
}

var tsKeywords = func() map[string]bool {
	out := make(map[string]bool)
	for _, value := range strings.Fields("break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with implements interface let package private protected public static yield await arguments eval") {
		out[value] = true
	}
	return out
}()

func pascal(value string) string {
	var out strings.Builder
	var words []string
	start := 0
	runes := []rune(value)
	flush := func(end int) {
		if end > start {
			words = append(words, string(runes[start:end]))
		}
		start = end
	}
	for i, r := range runes {
		if r == '_' {
			flush(i)
			start = i + 1
			continue
		}
		if i > start && unicode.IsUpper(r) && (unicode.IsLower(runes[i-1]) || unicode.IsDigit(runes[i-1]) || i+1 < len(runes) && unicode.IsLower(runes[i+1])) {
			flush(i)
		}
	}
	flush(len(runes))
	for _, part := range words {
		runes := []rune(strings.ToLower(part))
		if len(runes) != 0 {
			runes[0] = unicode.ToUpper(runes[0])
			out.WriteString(string(runes))
		}
	}
	return out.String()
}

func lowerCamel(value string) string {
	value = pascal(value)
	if value == "" {
		return ""
	}
	runes := []rune(value)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}
